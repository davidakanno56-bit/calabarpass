export function getHotelBaseRate(priceRange) {
  if (!priceRange) return 75000;
  const match = priceRange.match(/[\d,]+/);
  if (match) {
    const parsed = parseInt(match[0].replace(/,/g, ''), 10);
    return isNaN(parsed) ? 75000 : parsed;
  }
  return 75000;
}

